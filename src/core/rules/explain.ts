// Rule help as Markdown: the full page for "SCA: Explain Rule" and a short block for hovers.

import { RuleInfo, ruleInfo, RULES } from "./registry";

const KIND_LABEL: Record<RuleInfo["kind"], string> = {
  "run-time": "Run-time error",
  "coding-rule": "Coding rule",
  metric: "Metric",
};

/** The full explanation of a rule, or a short note for an unknown ID. */
export function explainRule(id: string): string {
  const r = ruleInfo(id);
  if (!r) {
    return `# ${id}\n\nSCA has no description for this rule.\n`;
  }
  const lines = [
    `# ${r.title}`,
    "",
    `\`${r.id}\` · ${KIND_LABEL[r.kind]} · ${r.group}${r.enabledByDefault ? "" : " · off by default"}`,
    "",
    r.summary,
    "",
    "## Why",
    "",
    r.rationale,
    "",
    "## How to fix",
    "",
    r.fix,
  ];
  if (r.limit !== undefined) {
    const key = r.id.split(":")[1];
    lines.push("", "## Limit", "", `Default: **${r.limit}**. Change it in \`.sca.json\`: \`"metrics": { "${key}": ${r.limit} }\`.`);
  }
  if (r.bad) {
    lines.push("", "## Example", "", "Breaks the rule:", "", "```c", r.bad, "```");
  }
  if (r.good) {
    lines.push("", "Follows the rule:", "", "```c", r.good, "```");
  }
  lines.push(
    "",
    "## Turning it off",
    "",
    `For one line: \`/* sca-justify(${r.id}): reason */\` on the line or the line above. For the project: \`"rules": { "${r.id}": ${r.enabledByDefault ? "false" : "true"} }\` in \`.sca.json\`${r.enabledByDefault ? "" : " turns it on"}.`
  );
  return lines.join("\n") + "\n";
}

/** Two lines for a hover: title and summary, plus the fix. */
export function ruleHover(id: string): string | undefined {
  const r = ruleInfo(id);
  return r ? `**${r.title}** (\`${r.id}\`)\n\n${r.summary} ${r.fix}` : undefined;
}

/** The rule reference (docs/rules.md): every rule, grouped. */
export function ruleReference(): string {
  const out = [
    "# SCA rule reference",
    "",
    "<!-- Generated by `npm run catalog` from src/core/rules/registry.ts. Do not edit by hand. -->",
    "",
    "Every rule SCA reports, with a description in our own words. In VS Code, hover a finding or run",
    "**SCA: Explain Rule** to see the same text.",
    "",
  ];
  const groups = [...new Set(RULES.map((r) => r.group))];
  for (const g of groups) {
    const rules = RULES.filter((r) => r.group === g);
    out.push(`## ${g}`, "", "| Rule | What it finds | Default |", "|---|---|---|");
    for (const r of rules) {
      out.push(`| [\`${r.id}\`](#${anchor(r.id)}) | ${r.summary} | ${r.enabledByDefault ? "on" : "off"}${r.limit !== undefined ? `, limit ${r.limit}` : ""} |`);
    }
    out.push("");
    for (const r of rules) {
      out.push(`### ${r.id}`, "", `**${r.title}.** ${r.summary}`, "", `*Why:* ${r.rationale}`, "", `*Fix:* ${r.fix}`, "");
      if (r.bad && r.good) {
        out.push("```c", "/* breaks the rule */", r.bad, "", "/* follows the rule */", r.good, "```", "");
      }
    }
  }
  return out.join("\n");
}

function anchor(id: string): string {
  return id.toLowerCase().replace(/[^a-z0-9 -]/g, "");
}
