// Generates the parts of the catalog and docs that describe implemented rules, from the rule registry
// (src/core/rules/registry.ts), so they always match the code.
//
//   npm run catalog            write the files
//   npm run catalog -- --check exit 1 when a file is out of date (used by the unit tests and CI)
//
// Generated:
//   catalog/rules.json                    every rule with its description (own words)
//   catalog/rulesets.json                 "implemented" / "implementedRules" of each rule set
//   catalog/README.md                     the status line between <!-- generated:status --> markers
//   catalog/coverage-presentation.html    the status paragraph between the same markers
//   docs/rules.md                         the rule reference

import * as fs from "fs";
import * as path from "path";
import { ruleReference } from "../core/rules/explain";
import { RULES } from "../core/rules/registry";

const START = "<!-- generated:status -->";
const END = "<!-- /generated:status -->";

/** Rule sets that have rules, with the short IDs of their rules in registry order. */
export function implementedSets(): Map<string, string[]> {
  const sets = new Map<string, string[]>();
  for (const r of RULES) {
    const [set, id] = r.id.split(":");
    sets.set(set, [...(sets.get(set) ?? []), id]);
  }
  return sets;
}

/** JSON with arrays of plain values on one line, like the hand-written catalog. */
export function stringifyCompact(value: unknown, indent = ""): string {
  const next = indent + "  ";
  if (Array.isArray(value)) {
    if (value.every((v) => v === null || typeof v !== "object")) {
      return `[${value.map((v) => JSON.stringify(v)).join(", ")}]`;
    }
    return `[\n${value.map((v) => next + stringifyCompact(v, next)).join(",\n")}\n${indent}]`;
  }
  if (value !== null && typeof value === "object") {
    const entries = Object.entries(value as Record<string, unknown>).filter(([, v]) => v !== undefined);
    if (entries.length === 0) {
      return "{}";
    }
    return `{\n${entries.map(([k, v]) => `${next}${JSON.stringify(k)}: ${stringifyCompact(v, next)}`).join(",\n")}\n${indent}}`;
  }
  return JSON.stringify(value);
}

function rulesJson(): string {
  const data = {
    $comment: "Generated by `npm run catalog` from src/core/rules/registry.ts. Do not edit by hand. Descriptions are SCA's own words.",
    version: 1,
    rules: RULES.map((r) => ({
      id: r.id,
      title: r.title,
      kind: r.kind,
      group: r.group,
      enabledByDefault: r.enabledByDefault,
      limit: r.limit,
      summary: r.summary,
      rationale: r.rationale,
      fix: r.fix,
    })),
  };
  return stringifyCompact(data) + "\n";
}

function rulesetsJson(current: string): string {
  const data = JSON.parse(current) as { ruleSets: { id: string; implemented: boolean; implementedRules?: string[] }[] };
  const sets = implementedSets();
  data.ruleSets = data.ruleSets.map((s) => {
    const rules = sets.get(s.id);
    const { implementedRules: _old, ...rest } = s;
    void _old;
    const reordered: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(rest)) {
      reordered[k] = k === "implemented" ? rules !== undefined : v;
      if (k === "implemented" && rules) {
        reordered.implementedRules = rules;
      }
    }
    return reordered as typeof s;
  });
  return stringifyCompact(data) + "\n";
}

function statusMarkdown(): string {
  const parts = [...implementedSets()].map(([set, ids]) => `\`${set}\` (${ids.length}: ${ids.map((i) => `\`${i}\``).join(", ")})`);
  return `> **Status:** the catalog shows the **target** coverage. Rule sets with at least one working rule have \`"implemented": true\` and list them in \`implementedRules\`: today ${parts.join(", ")}. Every rule is described in [rules.json](rules.json) and in the [rule reference](../docs/rules.md).`;
}

function statusHtml(): string {
  const parts = [...implementedSets()].map(([set, ids]) => `<code>${set}</code> (${ids.length}: ${ids.join(", ")})`);
  return `<p class="note"><b>Status:</b> this is the <b>target</b> coverage. Implemented today: ${parts.join(", ")}. Every rule is described in the rule reference (docs/rules.md).</p>`;
}

function replaceBlock(text: string, block: string, file: string): string {
  const a = text.indexOf(START);
  const b = text.indexOf(END);
  if (a < 0 || b < a) {
    throw new Error(`${file}: markers ${START} ... ${END} not found.`);
  }
  return text.slice(0, a + START.length) + "\n" + block + "\n" + text.slice(b);
}

/** Path (relative to the repo root) -> generated content. */
export function generateCatalog(root: string): Map<string, string> {
  const read = (p: string) => fs.readFileSync(path.join(root, p), "utf8").replace(/\r\n/g, "\n");
  const out = new Map<string, string>();
  out.set("catalog/rules.json", rulesJson());
  out.set("catalog/rulesets.json", rulesetsJson(read("catalog/rulesets.json")));
  out.set("catalog/README.md", replaceBlock(read("catalog/README.md"), statusMarkdown(), "catalog/README.md"));
  out.set("catalog/coverage-presentation.html", replaceBlock(read("catalog/coverage-presentation.html"), statusHtml(), "catalog/coverage-presentation.html"));
  out.set("docs/rules.md", ruleReference());
  return out;
}

/** Files whose content differs from what would be generated. */
export function staleFiles(root: string): string[] {
  const stale: string[] = [];
  for (const [p, content] of generateCatalog(root)) {
    const file = path.join(root, p);
    const now = fs.existsSync(file) ? fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") : undefined;
    if (now !== content) {
      stale.push(p);
    }
  }
  return stale;
}

function main(argv: string[]): number {
  const root = path.join(__dirname, "..", "..");
  if (argv.includes("--check")) {
    const stale = staleFiles(root);
    if (stale.length > 0) {
      console.error(`Out of date (run npm run catalog): ${stale.join(", ")}`);
      return 1;
    }
    console.log("Catalog is up to date.");
    return 0;
  }
  for (const [p, content] of generateCatalog(root)) {
    fs.mkdirSync(path.dirname(path.join(root, p)), { recursive: true });
    fs.writeFileSync(path.join(root, p), content);
    console.log(`wrote ${p}`);
  }
  return 0;
}

if (require.main === module) {
  process.exit(main(process.argv.slice(2)));
}
